/** The flags that have adjectives of their own in `tagAdj`. */
export const TAG_ADJECTIVE_FLAGS: ReadonlySet<string> = new Set(
  (TITLE_RULES.tagAdj ?? []).flatMap((alternative) => {
    const text = typeof alternative === 'string' ? alternative : alternative.t;
    return text.slice(0, Math.max(0, text.indexOf('?-'))).split(/[|&]/);
  }),
);
